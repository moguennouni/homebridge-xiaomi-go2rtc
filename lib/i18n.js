let language = 'en';

// "auto": French if the system locale is French, English otherwise
const setLanguage = (configured) => {
  if (configured === 'en' || configured === 'fr') {
    language = configured;
    return language;
  }
  let locale = process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || '';
  if (!locale) {
    try {
      locale = Intl.DateTimeFormat().resolvedOptions().locale;
    } catch {
      locale = '';
    }
  }
  language = /^fr/i.test(locale) ? 'fr' : 'en';
  return language;
};

const t = (key, params = {}) => {
  const template = MESSAGES[language][key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
};

module.exports = { t, setLanguage, MESSAGES };
